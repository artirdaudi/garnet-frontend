import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import AxeBuilder from '@axe-core/playwright';
const base = process.env.TEST_BASE_URL || 'http://localhost:3100';
await mkdir('artifacts', { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
await page.goto(`${base}/sq`);
await page.locator('.hero img').waitFor({ state: 'visible' });
await page.evaluate(() => document.fonts.ready);
await page.screenshot({ path: 'artifacts/home-desktop.png' });
await page.screenshot({ path: 'artifacts/home-full.png', fullPage: true });
for (const route of ['/en/projects', '/en/projects/residence-01', '/en/materials', '/en/materials/apollo', '/en/archstudio', '/en/showroom', '/en/about', '/en/contact']) {
  const response = await page.goto(base + route);
  assert.equal(response.status(), 200, route);
  assert.equal(await page.locator('h1').count(), 1, route);
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  assert.equal(overflow, false, `Desktop overflow: ${route}`);
  await page.screenshot({ path: `artifacts/${route.replaceAll('/', '-').slice(1)}.png` });
}
await page.goto(`${base}/en/projects`);
assert.equal(await page.locator('.project-card').count(), 8);
await page.getByRole('button', { name: 'Commercial' }).click();
assert.equal(await page.locator('.project-card').count(), 2);
await page.getByRole('button', { name: 'Architecture' }).click();
assert.equal(await page.locator('.project-card').count(), 3);
await page.locator('.project-card').first().click();
await page.waitForURL('**/en/projects/residence-01');
await page.locator('.desktop-languages').getByRole('link', { name: 'MK', exact: true }).click();
await page.waitForURL('**/mk/projects/residence-01');
assert.equal(await page.locator('html').getAttribute('lang'), 'mk');
assert.equal(await page.locator('h1').innerText(), 'Резиденција 01');
await page.goto(`${base}/en/projects/residence-01`);
await page.locator('.gallery button').first().click();
assert.equal(await page.locator('.lightbox').evaluate(el => el.open), true);
await page.keyboard.press('ArrowRight');
assert.equal(await page.locator('.lightbox-controls p').innerText(), '2 / 5');
await page.keyboard.press('Escape');
assert.equal(await page.locator('.lightbox').evaluate(el => el.open), false);
await page.locator('.material-card').first().click();
await page.waitForURL('**/en/materials/apollo');
await page.getByRole('link', { name: 'Ask about this material' }).click();
await page.waitForURL('**/en/contact?material=apollo');
assert.equal(await page.locator('.enquiry-material').innerText(), 'Materials: Apollo');
await page.getByRole('textbox', { name: 'Name', exact: false }).fill('Prototype review');
await page.getByRole('textbox', { name: 'Email', exact: false }).fill('demo@example.com');
await page.getByRole('textbox', { name: 'Message', exact: false }).fill('Please discuss this material.');
await page.getByRole('button', { name: 'Preview enquiry' }).click();
await page.getByText('Your enquiry is ready as a preview.', { exact: false }).waitFor();
await page.getByRole('button', { name: 'Edit enquiry' }).click();
assert.equal(await page.locator('[name="name"]').inputValue(), 'Prototype review');
await page.goto(`${base}/en/materials`);
await page.getByRole('button', { name: 'Decorative panels', exact: true }).click();
assert.equal(await page.locator('.material-card').count(), 1);
const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
await writeFile('artifacts/accessibility.json', JSON.stringify(axe.violations, null, 2));
console.log('Accessibility violations:', axe.violations.map(item => ({ id: item.id, nodes: item.nodes.length })));
for (const width of [375, 390, 768, 1024]) {
  await page.setViewportSize({ width, height: 844 });
  for (const route of ['/sq', '/mk', '/en/projects', '/en/projects/residence-01', '/en/materials', '/en/materials/apollo', '/mk/archstudio', '/en/showroom', '/mk/about', '/sq/contact']) {
    await page.goto(base + route);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Overflow ${width}: ${route}`);
    if (width === 390) await page.screenshot({ path: `artifacts/mobile-${route.replaceAll('/', '-').slice(1)}.png`, fullPage: true });
  }
}
await page.setViewportSize({ width: 390, height: 844 });
await page.goto(`${base}/en`);
await page.getByRole('button', { name: 'Open menu' }).click();
await page.screenshot({ path: 'artifacts/mobile-menu.png' });
assert.equal(await page.locator('.mobile-menu').evaluate(el => el.open), true);
await page.keyboard.press('Escape');
assert.equal(await page.locator('.mobile-menu').evaluate(el => el.open), false);
await page.getByRole('button', { name: 'Open menu' }).click();
await page.locator('.mobile-menu').getByRole('link', { name: 'Materials', exact: false }).click();
await page.waitForURL('**/en/materials');
assert.equal(await page.locator('.mobile-menu').evaluate(el => el.open), false);
console.log('Console errors:', errors);
assert.deepEqual(errors, []);
await browser.close();
console.log('Browser checks passed. Screenshots saved to artifacts/.');
